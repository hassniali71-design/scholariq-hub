-- ----------------------------------------------------------------------------
-- 4) تسجيل الطلاب الحقيقيين تلقائياً حسب صفهم واشتراكهم في المواد
-- ----------------------------------------------------------------------------
-- أول مادة (بترتيب subject_ids) بتبقى المجموعة الأساسية للطالب (students.group_id)
-- — بس للطلاب اللي معندهمش مجموعة أساسية أصلاً (group_id is null، وده حال كل
-- الطلاب المستوردين حالياً). أي مادة تانية بتتسجل في student_group_enrollments.

with matches as (
  select
    st.id as student_id,
    g.id as group_id,
    g.name as group_name,
    row_number() over (partition by st.id order by su.name) as rn
  from students st
  cross join lateral unnest(st.subject_ids) as subj_id(subject_id)
  join groups g
    on g.center_id = st.center_id
   and g.grade = st.grade
   and g.subject_id = subj_id.subject_id
  join subjects su on su.id = subj_id.subject_id
  where st.center_id = 'ctr-1789325195831'
)
-- 4-أ) المجموعة الأساسية (أول مادة) — فقط للطلاب اللي لسه معندهمش مجموعة
update students st
set group_id = m.group_id, group_name = m.group_name
from matches m
where st.id = m.student_id
  and m.rn = 1
  and st.group_id is null;

with matches as (
  select
    st.id as student_id,
    g.id as group_id,
    row_number() over (partition by st.id order by su.name) as rn
  from students st
  cross join lateral unnest(st.subject_ids) as subj_id(subject_id)
  join groups g
    on g.center_id = st.center_id
   and g.grade = st.grade
   and g.subject_id = subj_id.subject_id
  join subjects su on su.id = subj_id.subject_id
  where st.center_id = 'ctr-1789325195831'
)
-- 4-ب) أي مادة إضافية (مش الأولى) — تسجيل في student_group_enrollments
insert into student_group_enrollments (id, center_id, student_id, group_id)
select
  'sge-' || m.student_id || '-' || m.group_id as id,
  'ctr-1789325195831' as center_id,
  m.student_id,
  m.group_id
from matches m
where m.rn > 1
on conflict (student_id, group_id) do nothing;

-- ----------------------------------------------------------------------------
-- 5) تحديث عدد الطلاب الفعلي (enrolled) لكل مجموعة بعد التسجيل
-- ----------------------------------------------------------------------------
update groups g
set enrolled = (
  select count(*) from students st where st.group_id = g.id
)
where g.center_id = 'ctr-1789325195831';

