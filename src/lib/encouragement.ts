/** اختيار عبارة عشوائية حسب نتيجة الإجابة (صحيحة/خاطئة). */
export function pickEncouragement(correct: boolean): string {
  const pool = correct ? CORRECT_ENCOURAGEMENT : WRONG_ENCOURAGEMENT;
  return pool[Math.floor(Math.random() * pool.length)]!;
}
